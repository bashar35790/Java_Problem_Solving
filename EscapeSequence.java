public class EscapeSequence {
    public static void main(String[] args){
        System.out.println("Hello, World!\n Hello, World!");
        System.out.println("Hello, World!\t Hello, World!");
        System.out.println("Hello, World!\\ Hello, World!");
        System.out.println("Hello, World!\" Hello, World!");
        System.out.println("Hello, World!' Hello, World!");
    }
}